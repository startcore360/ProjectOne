-- 14_v41_audit_foundation.sql
-- PURPOSE: OD-09 audit foundation for the LEGACY public.audit_logs table.
--
-- Where audit rows belong (D4 §5.23 `app.audit_outbox`, Q-01, followed 2026-11-09):
--   * Tenant actions   -> app.audit_outbox (01_schema.sql; RLS p_tenant + p_institution and the
--                         append-only trg_audit_guard come from 03_bindings.sql). AuditLogService
--                         writes there whenever the request has a tenant and a signed-in tenant user.
--   * Platform actions -> platform.audit_outbox (PlatformAuditWriter).
--   * public.audit_logs is NOT a D4 table. It stays only as an append-only sink for events that
--     have no tenant user yet (platform requests that still call AuditLogService, sign-in attempts
--     before the user is known). No code reads it back and it is not the tenant audit store.
--
-- The shape below is exactly what the JPA entity audit.AuditLog maps (id bigint identity,
-- event_type, user_id, email, ip_address, occurred_at, details + the four OD-09 columns), so a
-- clean build, an older Hibernate-created table and prod ddl-auto=validate all agree.
-- Idempotent. Rollback: 14r_v41_audit_foundation_rollback.sql.

-- Repair: an earlier draft of this file created public.audit_logs with a UUID id and columns the
-- entity does not map (timestamp, actor_id, tenant_id text), so every insert failed. Replace that
-- shape only if it is empty; never drop audit rows.
DO $$
DECLARE
  n bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'audit_logs'
                AND column_name = 'id' AND data_type = 'uuid') THEN
    EXECUTE 'SELECT count(*) FROM public.audit_logs' INTO n;
    IF n > 0 THEN
      RAISE EXCEPTION 'public.audit_logs has the old UUID shape and % rows: export them, drop the table, then re-run 14 [Q-01]', n;
    END IF;
    DROP TABLE public.audit_logs;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_type varchar(255) NOT NULL,
    user_id bigint,
    email varchar(255) NOT NULL,
    ip_address varchar(255),
    occurred_at timestamp(6) with time zone NOT NULL,
    details text,
    actor_role_code varchar(64),
    scope_type varchar(32),
    institution_id uuid,
    correlation_id varchar(64),
    CONSTRAINT audit_logs_pkey PRIMARY KEY (id)
);

ALTER TABLE public.audit_logs
    ADD COLUMN IF NOT EXISTS actor_role_code VARCHAR(64),
    ADD COLUMN IF NOT EXISTS scope_type VARCHAR(32),
    ADD COLUMN IF NOT EXISTS institution_id UUID,
    ADD COLUMN IF NOT EXISTS correlation_id VARCHAR(64);

-- Older Hibernate tables made details varchar(255); longer details then failed to insert.
ALTER TABLE public.audit_logs ALTER COLUMN details TYPE text;

-- DB-A02: drop the restrictive legacy Hibernate enum check that blocks newer event types.
ALTER TABLE public.audit_logs
    DROP CONSTRAINT IF EXISTS audit_logs_event_type_check;

COMMENT ON TABLE public.audit_logs IS 'LEGACY append-only sink for audit events with no tenant user (OD-09). Not a D4 table: tenant audit is app.audit_outbox, platform audit is platform.audit_outbox [Q-01].';

CREATE OR REPLACE FUNCTION public.fn_audit_logs_guard()
RETURNS trigger AS $fn$
BEGIN
    RAISE EXCEPTION 'audit_logs is append-only: updates and deletes are prohibited [OD-09]';
END;
$fn$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_logs_guard ON public.audit_logs;
CREATE TRIGGER trg_audit_logs_guard
    BEFORE UPDATE OR DELETE ON public.audit_logs
    FOR EACH ROW EXECUTE FUNCTION public.fn_audit_logs_guard();
