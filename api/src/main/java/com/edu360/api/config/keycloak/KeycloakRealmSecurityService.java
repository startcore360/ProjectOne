package com.edu360.api.config.keycloak;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

/**
 * WHAT: puts one Keycloak realm into the EDU 360 sign-in security baseline (Sprint 1 batch B3),
 * idempotently - safe to run on every policy save, every new realm and every start-up:
 *
 * 1. Lockout (I-03, D1 NF-07): Keycloak brute-force protection on, temporary lockout of
 *    {@code lockoutMinutes} after {@code maxFailedLogins} failures inside a window of the same
 *    length (the policy has no separate window value). The failure count lives in Keycloak, so
 *    it is shared by every API node, survives an API restart and is cleared by Keycloak's own
 *    admin unlock (KeycloakAdminClient.clearBruteForceLockout).
 * 2. Password rules (I-06, R2-12): passwordPolicy = length(min) + notUsername (+ digits(1),
 *    specialChars(1) when the policy asks) + passwordBlacklist(file) when the denylist file is
 *    configured (KeycloakProperties.passwordDenylistName).
 * 3. Idle timeout (I-06): ssoSessionIdleTimeout = the policy's idle minutes.
 * 4. Two-step login (I-01, PD-8): TOTP policy compatible with Google Authenticator / Microsoft
 *    Authenticator (TOTP, HmacSHA1, 6 digits, 30 s) and the realm's direct-grant flow replaced by
 *    "edu360-direct-grant": Username -> Password -> [Conditional: user attribute mfa_required ==
 *    true -> OTP (REQUIRED)]. An account flagged mfa_required can never get a token without a
 *    valid code; one with no authenticator yet is refused (fail closed) until it enrols through
 *    Keycloak's own CONFIGURE_TOTP page.
 * 5. Password check (I-01/I-03): flow "edu360-password-check" (Username -> Password -> Deny
 *    access with message {@link #PASSWORD_VERIFIED_MESSAGE}) bound to the confidential client
 *    {@link #PASSWORD_CHECK_CLIENT_ID}. Lets the API learn "the password is right" without a
 *    session being created, so it can answer MFA_REQUIRED / MFA_ENROLMENT_REQUIRED only to a
 *    caller who has proven the password. Its secret is generated by Keycloak and read back via
 *    the admin API - there is no secret in code or configuration.
 *
 * The realm-export JSON files under docker/keycloak/ contain the same baseline for a fresh
 * Keycloak volume; this class brings every existing realm (and every realm created later by
 * TenantManagementService) to it.
 */
@Service
public class KeycloakRealmSecurityService {

    private static final Logger log = LoggerFactory.getLogger(KeycloakRealmSecurityService.class);

    public static final String DIRECT_GRANT_FLOW = "edu360-direct-grant";
    public static final String DIRECT_GRANT_TWO_STEP_SUBFLOW = "edu360-direct-grant-two-step";
    public static final String PASSWORD_CHECK_FLOW = "edu360-password-check";
    public static final String PASSWORD_CHECK_CLIENT_ID = "edu360-password-check";
    public static final String PASSWORD_VERIFIED_MESSAGE = "edu360_password_verified";
    static final String MFA_CONDITION_CONFIG_ALIAS = "edu360-mfa-required-attribute";
    static final String PASSWORD_VERIFIED_CONFIG_ALIAS = "edu360-password-verified";
    private static final String BUILT_IN_DIRECT_GRANT = "direct grant";

    /** The policy values this class needs (kept free of the platformops types on purpose). */
    public record RealmSecuritySettings(int minPasswordLength, boolean requireDigit, boolean requireSpecialChar,
                                        int maxFailedLogins, int lockoutMinutes, int idleSessionTimeoutMinutes) {
    }

    private final KeycloakAdminClient admin;
    private final KeycloakProperties properties;
    private final Map<String, String> passwordCheckSecrets = new ConcurrentHashMap<>();

    public KeycloakRealmSecurityService(KeycloakAdminClient admin, KeycloakProperties properties) {
        this.admin = admin;
        this.properties = properties;
    }

    // ------------------------------------------------------------------------------ apply

    public void apply(String realm, RealmSecuritySettings settings) {
        applyRealmSettings(realm, settings);
        ensureConfigureTotpEnabled(realm);
        ensureDirectGrantFlow(realm);
        String checkFlowId = ensurePasswordCheckFlow(realm);
        ensurePasswordCheckClient(realm, checkFlowId);
        passwordCheckSecrets.remove(realm);
        log.info("Applied EDU 360 sign-in security baseline to realm '{}'", realm);
    }

    /** The passwordPolicy string pushed to Keycloak for these settings. */
    public String passwordPolicyFor(RealmSecuritySettings settings) {
        List<String> parts = new ArrayList<>();
        parts.add("length(" + Math.max(8, settings.minPasswordLength()) + ")");
        parts.add("notUsername(undefined)");
        if (settings.requireDigit()) {
            parts.add("digits(1)");
        }
        if (settings.requireSpecialChar()) {
            parts.add("specialChars(1)");
        }
        String denylist = properties.getPasswordDenylistName();
        if (denylist != null && !denylist.isBlank()) {
            parts.add("passwordBlacklist(" + denylist.trim() + ")");
        }
        return String.join(" and ", parts);
    }

    /** Realm-level attributes of the baseline (exposed for tests and the realm export check). */
    public Map<String, Object> realmSettingsFor(RealmSecuritySettings settings) {
        int lockSeconds = Math.max(1, settings.lockoutMinutes()) * 60;
        Map<String, Object> rep = new LinkedHashMap<>();
        rep.put("bruteForceProtected", true);
        rep.put("permanentLockout", false);
        rep.put("failureFactor", Math.max(1, settings.maxFailedLogins()));
        rep.put("waitIncrementSeconds", lockSeconds);
        rep.put("maxFailureWaitSeconds", lockSeconds);
        rep.put("maxDeltaTimeSeconds", lockSeconds);
        rep.put("passwordPolicy", passwordPolicyFor(settings));
        rep.put("ssoSessionIdleTimeout", Math.max(1, settings.idleSessionTimeoutMinutes()) * 60);
        rep.put("otpPolicyType", "totp");
        rep.put("otpPolicyAlgorithm", "HmacSHA1");
        rep.put("otpPolicyDigits", 6);
        rep.put("otpPolicyPeriod", 30);
        rep.put("otpPolicyLookAheadWindow", 1);
        return rep;
    }

    private void applyRealmSettings(String realm, RealmSecuritySettings settings) {
        // Realm PUT is a partial update: only the fields sent are changed.
        admin.adminPut(realm, realmSettingsFor(settings));
    }

    @SuppressWarnings("unchecked")
    private void ensureConfigureTotpEnabled(String realm) {
        Map<String, Object> action = admin.adminGet(realm + "/authentication/required-actions/CONFIGURE_TOTP", Map.class);
        if (action != null && !Boolean.TRUE.equals(action.get("enabled"))) {
            Map<String, Object> updated = new HashMap<>(action);
            updated.put("enabled", true);
            admin.adminPut(realm + "/authentication/required-actions/CONFIGURE_TOTP", updated);
        }
    }

    // --------------------------------------------------------------- direct grant (two-step)

    static final List<String> DIRECT_GRANT_SHAPE = List.of(
            "0:direct-grant-validate-username:REQUIRED",
            "0:direct-grant-validate-password:REQUIRED",
            "0:flow=" + DIRECT_GRANT_TWO_STEP_SUBFLOW + ":CONDITIONAL",
            "1:conditional-user-attribute:REQUIRED:" + MFA_CONDITION_CONFIG_ALIAS,
            "1:direct-grant-validate-otp:REQUIRED");

    private void ensureDirectGrantFlow(String realm) {
        Map<String, Object> realmRep = admin.adminGet(realm, Map.class);
        if (!DIRECT_GRANT_SHAPE.equals(shapeOf(realm, DIRECT_GRANT_FLOW))) {
            if (DIRECT_GRANT_FLOW.equals(realmRep.get("directGrantFlow"))) {
                admin.adminPut(realm, Map.of("directGrantFlow", BUILT_IN_DIRECT_GRANT));
            }
            deleteFlowIfPresent(realm, DIRECT_GRANT_FLOW);
            createTopLevelFlow(realm, DIRECT_GRANT_FLOW, "EDU 360: password, then authenticator code for accounts with mfa_required=true (PD-8)");
            addExecution(realm, DIRECT_GRANT_FLOW, "direct-grant-validate-username", "REQUIRED");
            addExecution(realm, DIRECT_GRANT_FLOW, "direct-grant-validate-password", "REQUIRED");
            addSubFlow(realm, DIRECT_GRANT_FLOW, DIRECT_GRANT_TWO_STEP_SUBFLOW, "CONDITIONAL");
            String conditionId = addExecution(realm, DIRECT_GRANT_TWO_STEP_SUBFLOW, "conditional-user-attribute", "REQUIRED");
            admin.adminPost(realm + "/authentication/executions/" + conditionId + "/config", Map.of(
                    "alias", MFA_CONDITION_CONFIG_ALIAS,
                    "config", Map.of(
                            "attribute_name", KeycloakAdminClient.MFA_REQUIRED_ATTRIBUTE,
                            "attribute_expected_value", "true",
                            "not", "false",
                            "regex", "false",
                            "include_group_attributes", "false")));
            addExecution(realm, DIRECT_GRANT_TWO_STEP_SUBFLOW, "direct-grant-validate-otp", "REQUIRED");
        }
        if (!DIRECT_GRANT_FLOW.equals(admin.adminGet(realm, Map.class).get("directGrantFlow"))) {
            admin.adminPut(realm, Map.of("directGrantFlow", DIRECT_GRANT_FLOW));
        }
    }

    // ---------------------------------------------------------------------- password check

    static final List<String> PASSWORD_CHECK_SHAPE = List.of(
            "0:direct-grant-validate-username:REQUIRED",
            "0:direct-grant-validate-password:REQUIRED",
            "0:deny-access-authenticator:REQUIRED:" + PASSWORD_VERIFIED_CONFIG_ALIAS);

    @SuppressWarnings("unchecked")
    private String ensurePasswordCheckFlow(String realm) {
        if (!PASSWORD_CHECK_SHAPE.equals(shapeOf(realm, PASSWORD_CHECK_FLOW))) {
            findClient(realm).ifPresent(client -> {
                Map<String, Object> updated = new HashMap<>(client);
                updated.put("authenticationFlowBindingOverrides", Map.of());
                admin.adminPut(realm + "/clients/" + client.get("id"), updated);
            });
            deleteFlowIfPresent(realm, PASSWORD_CHECK_FLOW);
            createTopLevelFlow(realm, PASSWORD_CHECK_FLOW, "EDU 360: verifies a password without creating a session");
            addExecution(realm, PASSWORD_CHECK_FLOW, "direct-grant-validate-username", "REQUIRED");
            addExecution(realm, PASSWORD_CHECK_FLOW, "direct-grant-validate-password", "REQUIRED");
            String denyId = addExecution(realm, PASSWORD_CHECK_FLOW, "deny-access-authenticator", "REQUIRED");
            admin.adminPost(realm + "/authentication/executions/" + denyId + "/config", Map.of(
                    "alias", PASSWORD_VERIFIED_CONFIG_ALIAS,
                    "config", Map.of("denyErrorMessage", PASSWORD_VERIFIED_MESSAGE)));
        }
        return flowId(realm, PASSWORD_CHECK_FLOW);
    }

    private void ensurePasswordCheckClient(String realm, String flowId) {
        Map<String, Object> wanted = new LinkedHashMap<>();
        wanted.put("clientId", PASSWORD_CHECK_CLIENT_ID);
        wanted.put("name", "EDU 360 password check (API only)");
        wanted.put("description", "Confidential; direct grant bound to " + PASSWORD_CHECK_FLOW + ", which never issues a token");
        wanted.put("enabled", true);
        wanted.put("protocol", "openid-connect");
        wanted.put("publicClient", false);
        wanted.put("clientAuthenticatorType", "client-secret");
        wanted.put("standardFlowEnabled", false);
        wanted.put("implicitFlowEnabled", false);
        wanted.put("serviceAccountsEnabled", false);
        wanted.put("directAccessGrantsEnabled", true);
        wanted.put("authenticationFlowBindingOverrides", Map.of("direct_grant", flowId));

        var existing = findClient(realm);
        if (existing.isEmpty()) {
            admin.adminPost(realm + "/clients", wanted);
            return;
        }
        Map<String, Object> client = existing.get();
        boolean matches = wanted.entrySet().stream()
                .filter(e -> !e.getKey().equals("name") && !e.getKey().equals("description"))
                .allMatch(e -> e.getValue().equals(client.get(e.getKey())));
        if (!matches) {
            Map<String, Object> updated = new HashMap<>(client);
            updated.putAll(wanted);
            admin.adminPut(realm + "/clients/" + client.get("id"), updated);
        }
    }

    /**
     * The password-check client's secret, read from Keycloak (generated by Keycloak itself when
     * the client was created) and cached per realm until the next apply().
     */
    @SuppressWarnings("unchecked")
    public String passwordCheckSecret(String realm) {
        return passwordCheckSecrets.computeIfAbsent(realm, r -> {
            Map<String, Object> client = findClient(r).orElseThrow(() -> new KeycloakProvisioningException(
                    "Realm " + r + " has no " + PASSWORD_CHECK_CLIENT_ID + " client; run the realm security sync"));
            Map<String, Object> secret = admin.adminGet(r + "/clients/" + client.get("id") + "/client-secret", Map.class);
            Object value = secret == null ? null : secret.get("value");
            if (value == null || value.toString().isBlank()) {
                admin.adminPost(r + "/clients/" + client.get("id") + "/client-secret", Map.of());
                secret = admin.adminGet(r + "/clients/" + client.get("id") + "/client-secret", Map.class);
                value = secret == null ? null : secret.get("value");
            }
            if (value == null || value.toString().isBlank()) {
                throw new KeycloakProvisioningException("Keycloak returned no secret for " + PASSWORD_CHECK_CLIENT_ID + " in " + r);
            }
            return value.toString();
        });
    }

    /** True when the realm already has the two-step direct-grant flow in place and bound. */
    @SuppressWarnings("unchecked")
    public boolean isApplied(String realm) {
        Map<String, Object> realmRep = admin.adminGet(realm, Map.class);
        return realmRep != null && DIRECT_GRANT_FLOW.equals(realmRep.get("directGrantFlow"))
                && DIRECT_GRANT_SHAPE.equals(shapeOf(realm, DIRECT_GRANT_FLOW))
                && Boolean.TRUE.equals(realmRep.get("bruteForceProtected"));
    }

    // ----------------------------------------------------------------------------- helpers

    @SuppressWarnings("unchecked")
    private java.util.Optional<Map<String, Object>> findClient(String realm) {
        List<Map<String, Object>> clients = admin.adminGet(realm + "/clients?clientId=" + PASSWORD_CHECK_CLIENT_ID, List.class);
        return clients == null || clients.isEmpty() ? java.util.Optional.empty() : java.util.Optional.of(clients.get(0));
    }

    /** The flow's executions as "level:provider-or-flow:requirement[:configAlias]", or [] if absent. */
    @SuppressWarnings("unchecked")
    List<String> shapeOf(String realm, String alias) {
        if (flowIdOrNull(realm, alias) == null) {
            return List.of();
        }
        List<Map<String, Object>> executions = admin.adminGet(realm + "/authentication/flows/" + alias + "/executions", List.class);
        List<String> shape = new ArrayList<>();
        for (Map<String, Object> e : executions == null ? List.<Map<String, Object>>of() : executions) {
            String what = Boolean.TRUE.equals(e.get("authenticationFlow"))
                    ? "flow=" + e.get("displayName")
                    : String.valueOf(e.get("providerId"));
            String line = e.get("level") + ":" + what + ":" + e.get("requirement");
            if (e.get("alias") != null) {
                line += ":" + e.get("alias");
            }
            shape.add(line);
        }
        return shape;
    }

    private String flowId(String realm, String alias) {
        String id = flowIdOrNull(realm, alias);
        if (id == null) {
            throw new KeycloakProvisioningException("Flow " + alias + " missing in realm " + realm);
        }
        return id;
    }

    @SuppressWarnings("unchecked")
    private String flowIdOrNull(String realm, String alias) {
        List<Map<String, Object>> flows = admin.adminGet(realm + "/authentication/flows", List.class);
        if (flows == null) {
            return null;
        }
        return flows.stream().filter(f -> alias.equals(f.get("alias")))
                .map(f -> String.valueOf(f.get("id"))).findFirst().orElse(null);
    }

    private void deleteFlowIfPresent(String realm, String alias) {
        String id = flowIdOrNull(realm, alias);
        if (id != null) {
            admin.adminDelete(realm + "/authentication/flows/" + id);
        }
    }

    private void createTopLevelFlow(String realm, String alias, String description) {
        admin.adminPost(realm + "/authentication/flows", Map.of(
                "alias", alias,
                "description", description,
                "providerId", "basic-flow",
                "topLevel", true,
                "builtIn", false));
    }

    private void addSubFlow(String realm, String parentAlias, String alias, String requirement) {
        admin.adminPost(realm + "/authentication/flows/" + parentAlias + "/executions/flow", Map.of(
                "alias", alias,
                "description", "Asks for the authenticator code when the account has mfa_required=true",
                "provider", "registration-page-form",
                "type", "basic-flow"));
        setRequirement(realm, parentAlias, "flow=" + alias, requirement);
    }

    /** Adds an execution and sets its requirement; returns the execution id. */
    private String addExecution(String realm, String flowAlias, String provider, String requirement) {
        admin.adminPost(realm + "/authentication/flows/" + flowAlias + "/executions/execution", Map.of("provider", provider));
        return setRequirement(realm, flowAlias, provider, requirement);
    }

    @SuppressWarnings("unchecked")
    private String setRequirement(String realm, String flowAlias, String what, String requirement) {
        List<Map<String, Object>> executions = admin.adminGet(realm + "/authentication/flows/" + flowAlias + "/executions", List.class);
        Map<String, Object> target = null;
        for (Map<String, Object> e : executions) {
            String name = Boolean.TRUE.equals(e.get("authenticationFlow")) ? "flow=" + e.get("displayName") : String.valueOf(e.get("providerId"));
            if (name.equals(what) && Integer.valueOf(0).equals(e.get("level"))) {
                target = e; // the last match is the one just added
            }
        }
        if (target == null) {
            throw new KeycloakProvisioningException("Execution " + what + " not found in flow " + flowAlias + " of realm " + realm);
        }
        if (!requirement.equals(target.get("requirement"))) {
            Map<String, Object> updated = new HashMap<>(target);
            updated.put("requirement", requirement);
            admin.adminPut(realm + "/authentication/flows/" + flowAlias + "/executions", updated);
        }
        return String.valueOf(target.get("id"));
    }
}
