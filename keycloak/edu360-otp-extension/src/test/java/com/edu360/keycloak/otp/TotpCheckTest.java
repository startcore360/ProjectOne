package com.edu360.keycloak.otp;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.charset.StandardCharsets;

import org.junit.jupiter.api.Test;
import org.keycloak.models.OTPPolicy;
import org.keycloak.models.utils.Base32;
import org.keycloak.models.utils.HmacOTP;
import org.keycloak.models.utils.TimeBasedOTP;

class TotpCheckTest {

    private final OTPPolicy policy = OTPPolicy.DEFAULT_POLICY;

    // In Edu360OtpResource.start():
    // 1. secret is generated with HmacOTP.generateSecret(20) (raw ASCII chars)
    // 2. TotpUtils.encode(secret) gives Base32.encode(secret.getBytes()) to the user
    // 3. User scans or types Base32 string into Google/Microsoft Authenticator
    // 4. Authenticator app decodes Base32 back to bytes, exactly equal to secret.getBytes(UTF_8)
    // 5. Authenticator app generates TOTP using those bytes
    private String currentCode(String secret) {
        String base32String = Base32.encode(secret.getBytes(StandardCharsets.UTF_8));
        byte[] appDecodedKey = Base32.decode(base32String);
        return new TimeBasedOTP(policy.getAlgorithm(), policy.getDigits(), policy.getPeriod(),
                policy.getLookAheadWindow()).generateTOTP(appDecodedKey);
    }

    @Test
    void acceptsTheCurrentCodeForTheSecret() {
        String secret = HmacOTP.generateSecret(20);
        assertTrue(TotpCheck.isValid(currentCode(secret), secret, policy));
        assertTrue(TotpCheck.isValid(" " + currentCode(secret) + " ", secret, policy));
    }

    @Test
    void rejectsACodeForAnotherSecret() {
        String secret = HmacOTP.generateSecret(20);
        String other = HmacOTP.generateSecret(20);
        assertFalse(TotpCheck.isValid(currentCode(other), secret, policy)
                && !currentCode(other).equals(currentCode(secret)));
    }

    @Test
    void matchesKeycloakTotpEncoding() {
        String secret = HmacOTP.generateSecret(20);
        // Direct string overload of TimeBasedOTP uses secret.getBytes(StandardCharsets.UTF_8)
        String directCode = new TimeBasedOTP(policy.getAlgorithm(), policy.getDigits(), policy.getPeriod(),
                policy.getLookAheadWindow()).generateTOTP(secret);
        String appCode = currentCode(secret);
        // Verify that the code generated by an authenticator app (decoding the Base32 QR/manual secret)
        // is identical to TimeBasedOTP.generateTOTP(secret).
        assertTrue(appCode.equals(directCode));
        assertTrue(TotpCheck.isValid(appCode, secret, policy));
    }

    @Test
    void rejectsMalformedInput() {
        String secret = HmacOTP.generateSecret(20);
        assertFalse(TotpCheck.isValid(null, secret, policy));
        assertFalse(TotpCheck.isValid("12345", secret, policy));
        assertFalse(TotpCheck.isValid("12a456", secret, policy));
        assertFalse(TotpCheck.isValid("1234567", secret, policy));
        assertFalse(TotpCheck.isValid("123456", null, policy));
    }
}
